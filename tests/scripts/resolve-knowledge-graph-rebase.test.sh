#!/usr/bin/env bash
# Gate: scripts/knowledge-graph/resolve-rebase-conflict.sh stays callable and regenerates KG.
#
# Discovered bare by scripts/ci/run-repo-gates.sh (tests/scripts/*.test.sh).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
SCRIPT="${ROOT}/scripts/knowledge-graph/resolve-rebase-conflict.sh"
BUILDER="${ROOT}/scripts/knowledge-graph/build-knowledge-graph.py"

fail() { echo "FAIL: $*" >&2; exit 1; }

[[ -x "${SCRIPT}" || -f "${SCRIPT}" ]] || fail "missing ${SCRIPT}"
[[ -f "${BUILDER}" ]] || fail "missing ${BUILDER}"

# The helper intentionally stages generated files. Exercise it only inside a disposable
# clone: neither successful cleanup nor an early failure may overwrite the caller's work
# tree or index. Copy the current helper/builder so uncommitted changes are tested too.
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT
(
  unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE
  git clone --quiet --shared --no-hardlinks "${ROOT}" "${TMP}/repo"
)
cp "${SCRIPT}" "${TMP}/repo/scripts/knowledge-graph/resolve-rebase-conflict.sh"
cp "${BUILDER}" "${TMP}/repo/scripts/knowledge-graph/build-knowledge-graph.py"
cp "${BASH_SOURCE[0]}" "${TMP}/repo/tests/scripts/resolve-knowledge-graph-rebase.test.sh"
cd "${TMP}/repo"
unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE
SCRIPT="${TMP}/repo/scripts/knowledge-graph/resolve-rebase-conflict.sh"

# Executable bit is not required on Windows checkouts; bash can still run it.
bash "${SCRIPT}" --dry-run >"${TMP}/dry.out"
grep -q 'dry-run OK' "${TMP}/dry.out" || fail "dry-run did not report OK: $(cat "${TMP}/dry.out")"

# Unknown flag must fail closed (not silently ignore).
if bash "${SCRIPT}" --nope >"${TMP}/bad.out" 2>"${TMP}/bad.err"; then
  fail "unknown flag should exit non-zero"
fi
grep -qi 'unknown' "${TMP}/bad.err" || fail "unknown flag stderr should mention unknown"

# Corrupt only the disposable artifacts, then regenerate and stage them.
printf '{ "broken": true }\n' > docs/knowledge-graph.json
printf '# broken\n' > docs/knowledge-graph.md

bash "${SCRIPT}"

# Helper must have restored a real graph (schema_version / generated_by).
grep -q 'generated_by' docs/knowledge-graph.json || fail "json not regenerated"
grep -q 'knowledge-graph' docs/knowledge-graph.md || fail "md not regenerated"

# The staged bytes must be the regenerated bytes, without touching the source checkout.
git show :docs/knowledge-graph.json >"${TMP}/staged.json"
git show :docs/knowledge-graph.md >"${TMP}/staged.md"
cmp -s docs/knowledge-graph.json "${TMP}/staged.json" || fail "regenerated json not staged"
cmp -s docs/knowledge-graph.md "${TMP}/staged.md" || fail "regenerated md not staged"

if [[ "${KG_RESOLVE_REBASE_NESTED:-0}" != "1" ]]; then
  # Regression: invoking this test must preserve distinct staged and unstaged caller
  # artifacts, plus the entire index. The "caller" here is itself disposable; never
  # plant sentinels in the real developer checkout. One nested run avoids recursion.
  printf 'staged json sentinel\n' > docs/knowledge-graph.json
  printf 'staged md sentinel\n' > docs/knowledge-graph.md
  git add -- docs/knowledge-graph.json docs/knowledge-graph.md
  git show :docs/knowledge-graph.json >"${TMP}/sentinel-staged.json"
  git show :docs/knowledge-graph.md >"${TMP}/sentinel-staged.md"
  printf 'unstaged json sentinel\n' > docs/knowledge-graph.json
  printf 'unstaged md sentinel\n' > docs/knowledge-graph.md
  cp docs/knowledge-graph.json "${TMP}/sentinel-worktree.json"
  cp docs/knowledge-graph.md "${TMP}/sentinel-worktree.md"
  cp .git/index "${TMP}/sentinel-index"
  if ! KG_RESOLVE_REBASE_NESTED=1 bash tests/scripts/resolve-knowledge-graph-rebase.test.sh \
      >"${TMP}/preservation.log" 2>&1; then
    cat "${TMP}/preservation.log" >&2
    fail "nested preservation invocation failed"
  fi
  cmp -s docs/knowledge-graph.json "${TMP}/sentinel-worktree.json" || fail "caller json worktree changed"
  cmp -s docs/knowledge-graph.md "${TMP}/sentinel-worktree.md" || fail "caller md worktree changed"
  git show :docs/knowledge-graph.json >"${TMP}/after-staged.json"
  git show :docs/knowledge-graph.md >"${TMP}/after-staged.md"
  cmp -s "${TMP}/after-staged.json" "${TMP}/sentinel-staged.json" || fail "caller staged json changed"
  cmp -s "${TMP}/after-staged.md" "${TMP}/sentinel-staged.md" || fail "caller staged md changed"
  cmp -s .git/index "${TMP}/sentinel-index" || fail "caller index changed"
  echo "PASS: staged and unstaged sentinels and complete caller index preserved"
fi

echo "PASS: resolve-knowledge-graph-rebase"
